import { build } from 'esbuild';
import { mkdir, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'server', 'api');
const outputDir = path.join(root, 'api', 'ai');

const entries = (await readdir(sourceDir))
  .filter(name => name.endsWith('.ts') && !name.endsWith('.d.ts'))
  .sort();

if (entries.length === 0) {
  throw new Error('Tidak ada entry API di server/api.');
}

await rm(outputDir, { recursive: true, force: true });
await mkdir(outputDir, { recursive: true });

for (const entry of entries) {
  const name = entry.slice(0, -3);
  await build({
    entryPoints: [path.join(sourceDir, entry)],
    outfile: path.join(outputDir, `${name}.js`),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    minify: true,
    keepNames: true,
    legalComments: 'none',
    logLevel: 'warning',
    banner: {
      js: '// Generated by scripts/build-api.js. Do not edit manually.',
    },
  });
  console.log(`API bundled: api/ai/${name}.js`);
}
